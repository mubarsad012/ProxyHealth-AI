#!/usr/bin/env python3
"""Rewrite rules for serving the static web export on a plain static host (DEPLOYMENT §2.3).

`expo export --platform web` (``web.output: "static"``) writes one HTML file per route, and a
dynamic route keeps its brackets in the file name: ``result/[id].html``,
``result/[id]/chat.html`` … ``papers/member/[id].html``. EAS Hosting resolves those files for
``/result/<id>``; Netlify, Cloudflare Pages and Vercel do not, so a reload, a shared link or a
reminder/clerk deep link would get the host's 404. This script reads the export and emits the
rules those hosts need. Standard library only; run it with any Python 3.10+.

    python3 scripts/web-host-rules.py apps/mobile/dist            # print the _redirects rules
    python3 scripts/web-host-rules.py apps/mobile/dist --write    # write _redirects + 404.html
    python3 scripts/web-host-rules.py apps/mobile/dist --vercel   # print vercel.json rewrites
    python3 scripts/web-host-rules.py apps/mobile/dist --check    # exit 1 on a route with no rule
    python3 scripts/web-host-rules.py apps/mobile/dist --verify https://<preview-host>
                                                  # GET each rule on a deployed host (uses curl)

``_redirects`` (Netlify and Cloudflare Pages read the same syntax) gets one ``200`` rewrite per
dynamic route, most specific first, e.g. ``/result/:id/chat  /result/[id]/chat  200``. Targets have
no ``.html``: both hosts serve ``x.html`` for ``/x``, and Cloudflare Pages would answer a ``.html``
target with a 308 to the extension-less path. ``404.html`` is a copy of Expo Router's
``+not-found.html`` (the S18 screen), which Netlify, Cloudflare Pages and Vercel serve for unknown
paths. Rewrites never apply when a real file matches, so static routes are untouched.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

DYNAMIC_SEGMENT = re.compile(r"^\[(\.\.\.)?([A-Za-z0-9_]+)\]$")
SKIP_FILES = {"+not-found.html", "_sitemap.html", "404.html"}
HEADER = "# Generated by scripts/web-host-rules.py from the web export (DEPLOYMENT §2.3); no edits."
SAMPLE_VALUE = "sample-id"
# Every exported page mounts the app on <div id="root">; a host's own 404 page does not.
APP_MARKER = 'id="root"'


@dataclass(frozen=True)
class Rule:
    source: str  # host pattern, e.g. /result/:id/chat
    target: str  # the exported file's URL path without .html, e.g. /result/[id]/chat
    file: str  # the exported file, relative to the export root
    segments: int

    def vercel(self) -> dict[str, str]:
        return {"source": self.source.replace("*", ":rest*"), "destination": self.target}

    def sample_path(self) -> str:
        return re.sub(r":[A-Za-z0-9_]+|\*", SAMPLE_VALUE, self.source)


def is_dynamic(rel: Path) -> bool:
    return any(DYNAMIC_SEGMENT.match(p) for p in rel.with_suffix("").parts)


def route_segments(rel: Path) -> list[str]:
    parts = list(rel.with_suffix("").parts)
    if parts and parts[-1] == "index":
        parts = parts[:-1]
    return [p for p in parts if not (p.startswith("(") and p.endswith(")"))]  # route groups


def rules_for(dist: Path) -> list[Rule]:
    rules: dict[str, Rule] = {}
    for html in sorted(dist.rglob("*.html")):
        rel = html.relative_to(dist)
        if rel.name in SKIP_FILES or rel.parts[0] in ("_expo", "assets"):
            continue
        if not is_dynamic(rel):
            continue
        source_parts: list[str] = []
        for part in route_segments(rel):
            m = DYNAMIC_SEGMENT.match(part)
            if m is None:
                source_parts.append(part)
            elif m.group(1):  # [...rest] catch-all
                source_parts.append("*")
            else:
                source_parts.append(f":{m.group(2)}")
        target_parts = list(rel.with_suffix("").parts)
        if target_parts[-1] == "index":
            target_parts = target_parts[:-1]
        rule = Rule(
            source="/" + "/".join(source_parts),
            target="/" + "/".join(target_parts),
            file=rel.as_posix(),
            segments=len(source_parts),
        )
        rules.setdefault(rule.source, rule)
    # Most specific first: more segments, then static segments before placeholders.
    return sorted(
        rules.values(),
        key=lambda r: (-r.segments, r.source.count(":") + r.source.count("*"), r.source),
    )


def redirects_text(rules: list[Rule]) -> str:
    width = max((len(r.source) for r in rules), default=0) + 2
    twidth = max((len(r.target) for r in rules), default=0) + 2
    lines = [HEADER]
    lines += [f"{r.source.ljust(width)}{r.target.ljust(twidth)}200" for r in rules]
    return "\n".join(lines) + "\n"


def write(dist: Path, rules: list[Rule]) -> None:
    redirects = dist / "_redirects"
    existing = redirects.read_text("utf-8") if redirects.exists() else ""
    hand_written = existing.split(HEADER, 1)[0].rstrip("\n")  # our block (if any) is regenerated
    if hand_written:
        # Keep hand-written rules first (Netlify and Cloudflare use the first match), then ours.
        redirects.write_text(hand_written + "\n\n" + redirects_text(rules), "utf-8")
    else:
        redirects.write_text(redirects_text(rules), "utf-8")
    not_found = dist / "+not-found.html"
    if not_found.is_file():
        shutil.copyfile(not_found, dist / "404.html")
    print(
        f"wrote {redirects} ({len(rules)} rules)" + (" and 404.html" if not_found.is_file() else "")
    )


def check(dist: Path, rules: list[Rule]) -> list[str]:
    problems: list[str] = []
    covered = {r.file for r in rules}
    for html in sorted(dist.rglob("*.html")):
        rel = html.relative_to(dist)
        if rel.name in SKIP_FILES or not is_dynamic(rel):
            continue
        if rel.as_posix() not in covered:
            problems.append(f"no rule for {rel.as_posix()}")
    for r in rules:
        if (
            not (dist / (r.target.lstrip("/") + ".html")).is_file()
            and not (dist / r.target.lstrip("/") / "index.html").is_file()
        ):
            problems.append(f"{r.source}: target {r.target} has no file in the export")
    if not rules:
        problems.append("the export has no dynamic routes — did Expo Router's file naming change?")
    redirects = dist / "_redirects"
    if redirects.exists():
        text = redirects.read_text("utf-8")
        for r in rules:
            line = rf"^{re.escape(r.source)}\s+{re.escape(r.target)}\s+200\s*$"
            if not re.search(line, text, re.MULTILINE):
                problems.append(f"_redirects lacks: {r.source} {r.target} 200")
    return problems


def verify(base_url: str, rules: list[Rule]) -> list[str]:
    problems: list[str] = []
    base = base_url.rstrip("/")
    for r in rules:
        url = base + r.sample_path()
        out = subprocess.run(
            ["curl", "-sS", "-o", "-", "-w", "\n%{http_code}", "--max-time", "20", url],
            capture_output=True, text=True, check=False,
        )  # fmt: skip
        body, _, code = out.stdout.rpartition("\n")
        is_app = APP_MARKER in body
        if out.returncode != 0:
            problems.append(f"{url}: curl failed ({out.stderr.strip()})")
        elif code != "200" or not is_app:
            problems.append(f"{url}: HTTP {code}" + ("" if is_app else ", not the app"))
        else:
            print(f"ok  {url}")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("dist", type=Path, help="the web export directory (apps/mobile/dist)")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument(
        "--write", action="store_true", help="write _redirects and 404.html into DIST"
    )
    mode.add_argument(
        "--vercel", action="store_true", help='print the vercel.json "rewrites" array'
    )
    mode.add_argument("--verify", metavar="BASE_URL", help="GET every rule on a deployed host")
    ap.add_argument(
        "--check", action="store_true", help="exit 1 unless every dynamic route has a rule"
    )
    args = ap.parse_args(argv)

    dist: Path = args.dist
    if not (dist / "index.html").is_file():
        print(f"{dist} is not a web export (no index.html)", file=sys.stderr)
        return 2
    rules = rules_for(dist)
    if args.write:
        write(dist, rules)
    elif args.vercel:
        print(json.dumps({"cleanUrls": True, "rewrites": [r.vercel() for r in rules]}, indent=2))
    elif args.verify:
        problems = verify(args.verify, rules)
        if problems:
            print("\n".join(problems), file=sys.stderr)
            return 1
    elif not args.check:
        sys.stdout.write(redirects_text(rules))
    if args.check:
        problems = check(dist, rules)
        if problems:
            print("\n".join(problems), file=sys.stderr)
            return 1
        print(f"{len(rules)} dynamic routes, each with a rewrite")
    return 0


if __name__ == "__main__":
    sys.exit(main())
