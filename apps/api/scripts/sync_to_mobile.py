"""Deterministic generator of the mobile app's copies of ``apps/api/data`` (BUILD_PLAN §4.3).

Full version (WP7; CL-004, CL-015). Writes, and with ``--check`` only verifies:

* ``src/i18n/packs/<tag>.json`` + ``index.ts`` — byte copies of ``data/langpacks/<tag>.json``
  (``_*.json`` translator contexts skipped) and the static ``require`` map Metro needs.
* ``src/i18n/languages.ts`` — ``LanguageInfo`` records from ``data/languages.yaml``.
* ``assets/fonts/**`` — byte copies of ``data/fonts/``.
* ``assets/fixtures/manifest.json`` (``list[DemoFixture]``), ``<id>.png`` thumbnails (≤ 600 px
  wide), ``<id>.result.<lang>.json`` — the full ``AnalysisResult`` (``TroubleshootResult`` for
  the screenshot) produced by running the mock pipeline for every recorded language with the
  fixture's frozen ``today``, volatile ids/latency pinned — and ``index.ts`` (static ``require``
  map used by ``api/offline.ts`` and ``features/demo``).
* ``assets/resources/national_fallbacks.json`` — ``list[Resource]`` (English text only) for
  ``_meta.yaml.well_known_ids.offline_subset`` (RESOURCE_DB §7).
* ``locales/<tag>.json`` — permission strings (pack keys ``perm.camera``, ``perm.photos``,
  ``perm.notifications``) for every bundled pack that has them, in the key format ``app.json``
  ``locales`` expects (iOS usage-description keys; ``perm_notifications`` has no Info.plist key).

``--check`` writes nothing and exits 1 when any generated file is missing, differs, or a stray
file sits in a managed directory. Output is byte-deterministic for a given input tree.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

API_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = API_ROOT.parents[1]
MOBILE = REPO_ROOT / "apps" / "mobile"
DATA = API_ROOT / "data"
sys.path.insert(0, str(API_ROOT))

PACKS_OUT = MOBILE / "src" / "i18n" / "packs"
LANGUAGES_OUT = MOBILE / "src" / "i18n" / "languages.ts"
FONTS_OUT = MOBILE / "assets" / "fonts"
FIXTURES_OUT = MOBILE / "assets" / "fixtures"
RESOURCES_OUT = MOBILE / "assets" / "resources"
LOCALES_OUT = MOBILE / "locales"

# Every file in these directories is generated; anything else there is a stray.
MANAGED_DIRS = (PACKS_OUT, FONTS_OUT, FIXTURES_OUT, RESOURCES_OUT, LOCALES_OUT)

HEADER = "// GENERATED by apps/api/scripts/sync_to_mobile.py — do not edit; rerun the script.\n"
THUMB_WIDTH = 600

PERMISSION_KEYS = {
    "perm.camera": "NSCameraUsageDescription",
    "perm.photos": "NSPhotoLibraryUsageDescription",
    "perm.notifications": "perm_notifications",
}


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n").encode("utf-8")


def _ts_literal(value: Any) -> str:
    """JSON is a valid TypeScript object literal; keep indent=2 for readable diffs."""
    return json.dumps(value, indent=2, ensure_ascii=False)


def _ts_key(key: str) -> str:
    return json.dumps(key, ensure_ascii=False).replace('"', "'")


# --------------------------------------------------------------------------- packs, languages


def pack_tags() -> list[str]:
    packs_dir = DATA / "langpacks"
    return sorted(p.stem for p in packs_dir.glob("*.json") if not p.name.startswith("_"))


def packs_index_ts(tags: list[str]) -> bytes:
    lines = [
        HEADER,
        "// Static require map of the bundled language packs (BUILD_PLAN §4.3, D-25).",
        "",
        "// `en.json` is a flat key → string map; the other packs are full `LanguagePack` dumps",
        "// (`strings` holds the keys). `i18n/store.ts` `fromBundled` accepts both shapes.",
        "export type BundledPackStrings = Record<string, string>;",
        "export type BundledLanguagePack = { readonly strings: BundledPackStrings } & Readonly<",
        "  Record<string, unknown>",
        ">;",
        "export type BundledPack = BundledPackStrings | BundledLanguagePack;",
        "",
        "export const bundledPacks: Record<string, BundledPack> = {",
    ]
    lines.extend(
        f"  {_ts_key(tag)}: require('./{tag}.json') as BundledPack," for tag in tags
    )
    lines += [
        "};",
        "",
        "export const bundledPackTags: readonly string[] = Object.keys(bundledPacks);",
        "",
    ]
    return "\n".join(lines).encode("utf-8")


def languages_ts(seed: dict[str, dict[str, Any]], bundled: set[str]) -> bytes:
    records: dict[str, dict[str, Any]] = {}
    for tag, row in seed.items():
        records[tag] = {
            "tag": tag,
            "name_native": row["name_native"],
            "name_en": row["name_en"],
            "direction": row["direction"],
            "script": row.get("script"),
            "digit_system": row["digit_system"],
            "font_hint": row.get("font_hint"),
            "tier": row["tier"],
            "tts_tag": row.get("tts_tag"),
            "tts_fallback_tag": row.get("tts_fallback_tag"),
            "bundled": tag in bundled,
            # D-25: only `en` is human-authored at v1; every other pack is machine-translated.
            "machine_translated": tag != "en",
        }
    body = (
        f"{HEADER}"
        "// Language seed from apps/api/data/languages.yaml (BUILD_PLAN Appendix E) as "
        "`LanguageInfo` records.\n"
        "// `LANGUAGE_TAGS` keeps the YAML order (the language grid shows it); "
        "`LANGUAGES` is keyed by tag.\n\n"
        "import type { LanguageInfo } from '@/api/types';\n\n"
        f"export const LANGUAGE_TAGS: readonly string[] = {_ts_literal(list(seed))};\n\n"
        f"export const LANGUAGES: Record<string, LanguageInfo> = {_ts_literal(records)};\n"
    )
    return body.encode("utf-8")


def pack_strings(pack: dict[str, Any]) -> dict[str, Any]:
    """The key → string map of a pack file: flat (``en.json``) or ``LanguagePack.strings``."""
    strings = pack.get("strings")
    return strings if isinstance(strings, dict) else pack


def locale_file(tag: str, pack: dict[str, Any]) -> bytes | None:
    """``locales/<tag>.json`` when the pack carries every permission key (``en`` must)."""
    missing = [k for k in PERMISSION_KEYS if k not in pack]
    if missing:
        if tag == "en":
            raise SystemExit(f"en.json lacks permission keys: {', '.join(missing)}")
        return None
    return _json_bytes({out: pack[key] for key, out in PERMISSION_KEYS.items()})


# --------------------------------------------------------------------------- drift / write


def strays(outputs: dict[Path, bytes]) -> list[Path]:
    found: list[Path] = []
    for directory in MANAGED_DIRS:
        if not directory.is_dir():
            continue
        for path in sorted(directory.rglob("*")):
            if path.is_file() and path not in outputs and path.name != ".DS_Store":
                found.append(path)
    return found


def drift(outputs: dict[Path, bytes]) -> list[tuple[str, Path]]:
    problems: list[tuple[str, Path]] = []
    for path, content in outputs.items():
        if not path.is_file():
            problems.append(("missing", path))
        elif path.read_bytes() != content:
            problems.append(("differs", path))
    problems.extend(("stray", p) for p in strays(outputs))
    return problems


def write_outputs(outputs: dict[Path, bytes]) -> int:
    changed = 0
    for path, content in outputs.items():
        if path.is_file() and path.read_bytes() == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        changed += 1
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    for stray in strays(outputs):
        stray.unlink()
        changed += 1
        print(f"removed {stray.relative_to(REPO_ROOT)}")
    return changed


# --------------------------------------------------------------------------- fixtures, resources


def thumbnail(png: bytes) -> bytes:
    import io

    from PIL import Image

    with Image.open(io.BytesIO(png)) as img:
        rgb = img.convert("RGB")
        height = round(rgb.height * THUMB_WIDTH / rgb.width)
        small = rgb.resize((THUMB_WIDTH, height), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def _pin_volatile(result: dict[str, Any], fixture_id: str, lang: str) -> dict[str, Any]:
    """Ids and latency differ per run; pin them so the bundle is byte-deterministic."""
    result["request_id"] = f"offline-{fixture_id}-{lang}"
    if "analysis_id" in result:
        result["analysis_id"] = f"sample-{fixture_id}-{lang}"
    meta = result.get("model_meta")
    if isinstance(meta, dict):
        meta["latency_ms"] = 0
    return result


async def _recorded_results() -> dict[tuple[str, str], dict[str, Any]]:
    """Run the mock pipeline for every fixture × recorded language (the offline bundle)."""
    import base64
    import dataclasses
    import logging
    import tempfile
    from datetime import UTC, datetime, time

    from proxyhealth_api.ai.failover import AIService
    from proxyhealth_api.ai.mock import MockProvider
    from proxyhealth_api.analysis.pipeline import PipelineDeps, run_analysis
    from proxyhealth_api.analysis.troubleshoot_pipeline import run_troubleshoot
    from proxyhealth_api.contracts.analysis import AnalyzeRequest
    from proxyhealth_api.contracts.common import PageInput
    from proxyhealth_api.contracts.troubleshoot import TroubleshootRequest
    from proxyhealth_api.demo.fixtures import FixtureStore
    from proxyhealth_api.resources.loader import ResourceRepo
    from proxyhealth_api.resources.rules_repo import RulesRepo
    from proxyhealth_api.settings import Settings

    logging.getLogger("proxyhealth").setLevel(logging.ERROR)
    store = FixtureStore.load(DATA / "fixtures")
    resources = ResourceRepo.load(DATA / "resources")
    rules = RulesRepo.load(DATA / "rules")
    results: dict[tuple[str, str], dict[str, Any]] = {}
    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(
            _env_file=None, ai_provider="mock", var_dir=Path(tmp), mock_latency_min_ms=0,
            mock_latency_max_ms=0,
        )  # fmt: skip
        ai = AIService(MockProvider(store, settings), None, settings)
        for fx in store.all():
            moment = datetime.combine(fx.today, time(14, 0), tzinfo=UTC)
            known: dict[str, Any] = {
                "settings": settings, "ai": ai, "resources": resources, "rules": rules,
                "fixtures": store, "request_id": f"offline-{fx.id}",
                "data_use_tier": settings.data_use_tier, "clock": lambda m=moment: m,
            }  # fmt: skip
            deps = PipelineDeps(
                **{f.name: known[f.name] for f in dataclasses.fields(PipelineDeps)
                   if f.name in known}  # fmt: skip
            )
            for lang in fx.languages:
                if fx.kind == "screenshot":
                    shot = PageInput.model_validate({
                        "mime_type": "image/png",
                        "data_base64": base64.b64encode(fx.page_png(1)).decode("ascii"),
                    })  # fmt: skip
                    t_req = TroubleshootRequest(
                        screenshot=shot, target_language=lang, client_platform="web",
                        demo_sample_id=fx.id,
                    )  # fmt: skip
                    body = (await run_troubleshoot(t_req, deps)).model_dump(mode="json")
                else:
                    a_req = AnalyzeRequest(
                        pages=[], target_language=lang, client_platform="web",
                        demo_sample_id=fx.id, analysis_id=f"sample-{fx.id}-{lang}",
                        state=fx.expected.get("state"),
                    )  # fmt: skip
                    body = (await run_analysis(a_req, deps)).model_dump(mode="json")
                results[(fx.id, lang)] = _pin_volatile(body, fx.id, lang)
    return results


def fixtures_index_ts(entries: list[tuple[str, list[str]]]) -> bytes:
    lines = [
        HEADER,
        "// Offline sample assets (BUILD_PLAN §4.3): thumbnails and recorded results per fixture.",
        "// Results are full AnalysisResult / TroubleshootResult bodies from the mock pipeline.",
        "",
        "import type { DemoFixture } from '@/api/types';",
        "",
        "export type FixtureAssets = {",
        "  /** `require('./<id>.png')` thumbnail (≤ 600 px) or null when none is bundled. */",
        "  thumbnail: number | null;",
        "  /** language tag → `require('./<id>.result.<lang>.json')` "
        "(AnalysisResult | TroubleshootResult). */",
        "  results: Record<string, unknown>;",
        "};",
        "",
        "export const fixtureManifest: DemoFixture[] = require('./manifest.json');",
        "",
        "export const fixtureAssets: Record<string, FixtureAssets> = {",
    ]
    for fid, langs in entries:
        lines.append(f"  {_ts_key(fid)}: {{")
        lines.append(f"    thumbnail: require('./{fid}.png'),")
        lines.append("    results: {")
        lines.extend(
            f"      {_ts_key(lang)}: require('./{fid}.result.{lang}.json'),"
            for lang in langs
        )
        lines.append("    },")
        lines.append("  },")
    lines += ["};", ""]
    return "\n".join(lines).encode("utf-8")


def fixture_outputs() -> dict[Path, bytes]:
    import asyncio

    from proxyhealth_api.demo.fixtures import FixtureStore

    store = FixtureStore.load(DATA / "fixtures")
    outputs: dict[Path, bytes] = {}
    manifest = [f.manifest.model_dump(mode="json") for f in store.all()]
    outputs[FIXTURES_OUT / "manifest.json"] = _json_bytes(manifest)
    results = asyncio.run(_recorded_results())
    entries: list[tuple[str, list[str]]] = []
    for fx in store.all():
        outputs[FIXTURES_OUT / f"{fx.id}.png"] = thumbnail(fx.page_png(1))
        for lang in fx.languages:
            path = FIXTURES_OUT / f"{fx.id}.result.{lang}.json"
            outputs[path] = _json_bytes(results[(fx.id, lang)])
        entries.append((fx.id, fx.languages))
    outputs[FIXTURES_OUT / "index.ts"] = fixtures_index_ts(entries)
    return outputs


def national_fallbacks() -> bytes:
    """RESOURCE_DB §7 offline subset, English text only, in ``offline_subset`` order."""
    from proxyhealth_api.resources.loader import ResourceRepo

    repo = ResourceRepo.load(DATA / "resources")
    rows: list[dict[str, Any]] = []
    for rid in repo.well_known_ids("offline_subset"):
        res = repo.get(rid)
        if res is None:
            raise SystemExit(f"offline_subset names an unknown resource id: {rid}")
        row = res.model_dump(mode="json")
        for field_name in ("what_it_does", "eligibility_plain"):
            text = row.get(field_name) or {}
            row[field_name] = {"en": text["en"]} if "en" in text else {}
        rows.append(row)
    return _json_bytes(rows)


def build_outputs() -> dict[Path, bytes]:
    outputs: dict[Path, bytes] = {}
    tags = pack_tags()
    for tag in tags:
        outputs[PACKS_OUT / f"{tag}.json"] = (DATA / "langpacks" / f"{tag}.json").read_bytes()
    outputs[PACKS_OUT / "index.ts"] = packs_index_ts(tags)

    with (DATA / "languages.yaml").open(encoding="utf-8") as fh:
        seed: dict[str, dict[str, Any]] = yaml.safe_load(fh)
    outputs[LANGUAGES_OUT] = languages_ts(seed, set(tags))

    for font in sorted(p for p in (DATA / "fonts").iterdir() if p.is_file()):
        outputs[FONTS_OUT / font.name] = font.read_bytes()

    for tag in tags:
        pack: dict[str, Any] = json.loads((DATA / "langpacks" / f"{tag}.json").read_text("utf-8"))
        locale = locale_file(tag, pack_strings(pack))
        if locale is not None:
            outputs[LOCALES_OUT / f"{tag}.json"] = locale

    outputs.update(fixture_outputs())
    outputs[RESOURCES_OUT / "national_fallbacks.json"] = national_fallbacks()
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="verify the generated files; exit 1 on drift"
    )
    args = parser.parse_args(argv)
    outputs = build_outputs()
    if args.check:
        problems = drift(outputs)
        for kind, path in problems:
            print(f"{kind}: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        if problems:
            print(
                f"{len(problems)} generated file(s) out of date — run "
                "apps/api/.venv/bin/python apps/api/scripts/sync_to_mobile.py",
                file=sys.stderr,
            )
            return 1
        print(f"in sync ({len(outputs)} files)")
        return 0
    changed = write_outputs(outputs)
    print(f"{changed} file(s) changed, {len(outputs)} managed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
